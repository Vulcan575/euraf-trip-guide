function getTransportCost(a,b){
  if(a===b) return 150;
  const k = a+'|'+b;
  if(transportCost[k]!==undefined) return transportCost[k];
  if(transportCost[b+'|'+a]!==undefined) return transportCost[b+'|'+a];
  return 500;
}

