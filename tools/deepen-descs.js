const fs = require('fs');
const path = 'js/data-cities.js';
let code = fs.readFileSync(path, 'utf8');
let ok = 0, miss = [];
for (const [city, spot, oldD, newD] of fixes) {
  const key = spot + ':' + oldD;
  if (code.includes(key)) {
    code = code.split(key).join(spot + ':' + newD);
    ok++;
  } else {
    miss.push(city + ' | ' + spot + ' | ' + oldD);
  }
}
